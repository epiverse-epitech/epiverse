-- ---- Identity & access ----

CREATE TABLE users (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    public_id         UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    pseudonym_id      UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    first_name        VARCHAR(50) NOT NULL,
    last_name         VARCHAR(50) NOT NULL,
    email             VARCHAR(255) NOT NULL,
    email_verified_at TIMESTAMPTZ,
    password_hash     VARCHAR(255) NOT NULL,
    school_id         INTEGER,
    company_id        INTEGER,
    avatar_media_id   INTEGER,
    is_active         BOOLEAN NOT NULL DEFAULT true,
    visibility        profile_visibility NOT NULL DEFAULT 'private',
    last_login_at     TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at        TIMESTAMPTZ,
    anonymized_at     TIMESTAMPTZ,
    CONSTRAINT pk_users PRIMARY KEY (id)
);
COMMENT ON COLUMN users.public_id IS 'id exposed in URLs and API, default gen_random_uuid()';
COMMENT ON COLUMN users.pseudonym_id IS 'pseudonymous id sent to the recommender pipeline instead of id / e-mail';
COMMENT ON COLUMN users.email IS 'stored lowercased; UNIQUE on lower(email) in SQL';
COMMENT ON COLUMN users.email_verified_at IS 'NULL = not verified (FR-AUTH-005)';
COMMENT ON COLUMN users.school_id IS 'NULL = not attached to a school';
COMMENT ON COLUMN users.company_id IS 'set for company representatives';
COMMENT ON COLUMN users.avatar_media_id IS 'profile picture, NULL = default avatar';
COMMENT ON COLUMN users.visibility IS 'profile visibility, private by default (NFR-PRIV-002): public / same school only / private';
COMMENT ON COLUMN users.deleted_at IS 'soft delete, followed by anonymisation after a delay';
COMMENT ON COLUMN users.anonymized_at IS 'personal data wiped after the retention delay';

